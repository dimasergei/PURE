'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const { randomUUID } = require('node:crypto');
const { PGlite } = require('@electric-sql/pglite');
const { base, polygon, read } = require('./fixtures/commerce-sql-fixture.cjs');

test('gift orders reconcile bank receipts, account claims, partial spending and refunds', {timeout:60000}, async () => {
  const db=new PGlite();
  try {
    await base(db);await polygon(db);
    await db.exec("alter table cron.job add column active boolean default true");
    await db.exec(read('20261126170000_purchased_gift_cards.sql'));
    const method=randomUUID(), buyer=randomUUID(), recipient=randomUUID();
    const sql=(q,p)=>db.query(q,p);
    const date=(await sql("select (now() at time zone 'UTC')::date::text as today",[])).rows[0].today;
    await sql("insert into public.commerce_payment_methods(id,kind,label,currency,payee,instructions,acceptance_reference,active,provider_key) values($1,'bank_transfer','Bank wire','USD','Fixture business','Test routing instructions','Fixture verified',true,'bank_transfer')",[method]);
    const purchase=(id,extra={})=>sql('select public.pure_gift_create($1::jsonb)',[JSON.stringify({id,purchaser_id:buyer,purchaser_email:'buyer@example.test',recipient_email:'recipient@example.test',amount_cents:2525,digest:'a'.repeat(64),consent:true,method_id:method,send_date:date,...extra})]);
    const move=(id,action,data={})=>sql('select public.pure_gift_transition($1,$2,$3::jsonb) as state',[id,action,JSON.stringify(data)]).then(r=>r.rows[0].state);
    const transfer=reference=>({reference,currency:'USD',amount_cents:2525,confirmed:true});
    const claim={customer_id:recipient,email:'recipient@example.test'};
    const balance=()=>sql('select credit_cents from public.commerce_balance_accounts where customer_id=$1',[recipient]).then(r=>r.rows[0]?.credit_cents||0);
    const id=randomUUID(), second=randomUUID();
    assert.equal((await sql('select public.pure_gift_delivery_ready() as ok',[])).rows[0].ok,false);
    await sql("insert into vault.decrypted_secrets values('altapure_invoice_worker',$1)",['x'.repeat(32)]);
    assert.equal((await sql('select public.pure_gift_delivery_ready() as ok',[])).rows[0].ok,true);
    assert.equal((await sql('select commerce_internal.dispatch_due_gift_mail() as job',[])).rows[0].job,null);
    const cancelled=randomUUID();await purchase(cancelled);
    await assert.rejects(move(cancelled,'cancel',{customer_id:recipient,confirmed:true}),/not found/);
    await move(cancelled,'cancel',{customer_id:buyer,confirmed:true});await move(cancelled,'cancel',{customer_id:buyer,confirmed:true});
    await assert.rejects(move(cancelled,'fund',transfer('bank-cancelled')),/changed/);
    await purchase(id);await purchase(id);
    await assert.rejects(purchase(id,{digest:'b'.repeat(64)}),/changed/);
    await assert.rejects(move(id,'claim',claim),/not available/);
    await assert.rejects(move(id,'fund',{...transfer('bank-pay-1'),amount_cents:2524}),/exact USD/);
    assert.equal(await move(id,'fund',transfer('bank-pay-1')),'funded');
    assert.equal(await move(id,'fund',transfer('bank-pay-1')),'funded');
    const lease=randomUUID();
    assert.equal(await move(id,'notify_claim',{lease}),'send');
    assert.equal(await move(id,'notify_claim',{lease:randomUUID()}),'skip');
    await assert.rejects(move(id,'refund_start',{confirmed:true}),/in progress/);
    await move(id,'notify_failed',{lease});
    await sql("update public.pure_gift_orders set notify_after=now()-interval '1 minute',first_attempt_at=now()-interval '25 hours' where id=$1",[id]);
    assert.equal(await move(id,'notify_claim',{lease}),'review');
    await assert.rejects(move(id,'notify_reset',{}),/Verify prior/);
    await move(id,'notify_reset',{confirmed:true});
    assert.equal(await move(id,'notify_claim',{lease}),'send');
    await move(id,'notify_accepted',{lease,provider_id:'fixture-email'});
    assert.equal(await move(id,'notify_claim',{lease}),'skip');
    await assert.rejects(move(id,'claim',{...claim,email:'wrong@example.test'}),/not available/);
    assert.equal(await move(id,'claim',claim),'claimed');
    assert.equal(await move(id,'claim',claim),'claimed');
    assert.equal(await balance(),2525);
    await purchase(second);
    await assert.rejects(move(second,'fund',transfer('BANK-PAY-1')),/already recorded/);
    await move(second,'fund',transfer('bank-pay-2'));await move(second,'claim',claim);
    assert.equal(await balance(),5050);
    await move(id,'refund_start',{confirmed:true});await move(id,'refund_start',{confirmed:true});
    assert.equal(await balance(),2525);
    await assert.rejects(move(id,'claim',claim),/not available/);
    await assert.rejects(move(id,'refund_finish',transfer('bank-pay-2')),/already recorded/);
    assert.equal(await move(id,'refund_finish',transfer('bank-return-1')),'refunded');
    assert.equal(await move(id,'refund_finish',transfer('bank-return-1')),'refunded');
    await sql("select commerce_internal.balance_event($1,null,'credit',-1000,'Checkout redemption','checkout-fixture-1','test')",[recipient]);
    assert.equal(await balance(),1525);
    await assert.rejects(move(second,'refund_start',{confirmed:true}),/spent/);
    const future=randomUUID();
    const delivery=(await sql("select ((now() at time zone 'UTC')::date+2)::text as d",[])).rows[0].d;
    await purchase(future,{send_date:delivery});await move(future,'fund',transfer('bank-pay-3'));
    assert.equal(await move(future,'notify_claim',{lease:randomUUID()}),'skip');
    await assert.rejects(move(future,'claim',claim),/not available/);
    await move(future,'refund_start',{confirmed:true});await move(future,'refund_finish',transfer('bank-return-3'));
    await assert.rejects(move(future,'claim',claim),/not available/);
    const regularId=randomUUID();
    await sql("insert into public.commerce_invoices(id,customer_id,customer_email,customer_name,kind,request_digest,request_data) values($1,$2,'buyer@example.test','Test buyer','goods',$3,'{}')",[regularId,buyer,'c'.repeat(64)]);
    const ordinary=reference=>sql("insert into public.commerce_receipts(id,invoice_id,kind,method_id,external_reference,amount_cents,currency,actor) values($1,$2,'payment',$3,$4,2525,'USD','test')",[randomUUID(),regularId,method,reference]);
    await assert.rejects(ordinary('BANK-PAY-1'),/already recorded/);await ordinary('regular-bank-ref');
    const last=randomUUID();await purchase(last);
    await assert.rejects(move(last,'fund',transfer('Regular-Bank-Ref')),/already recorded/);
    await sql('update public.commerce_payment_methods set active=false where id=$1',[method]);
    await assert.rejects(purchase(randomUUID()),/unavailable/);
    const grants=await sql("select has_function_privilege('authenticated','public.pure_gift_transition(uuid,text,jsonb)','EXECUTE') as customer_exec,has_function_privilege('service_role','public.pure_gift_transition(uuid,text,jsonb)','EXECUTE') as service_exec",[]);
    assert.deepEqual(grants.rows[0],{customer_exec:false,service_exec:true});
  } finally {await db.close();}
});
